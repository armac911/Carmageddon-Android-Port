"""Generate immutable native/Java catalogues from reviewed UTF-8 JSON."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'localization/catalog.json').read_text())
rows={}
for key,translations in data['strings'].items():
 assert set(translations)=={'es','it','fr'}
 assert all(v and '\x00' not in v and set(v.count('{'+x+'}') for x in ['game'])=={key.count('{game}')} for v in translations.values())
 rows[key]=[key]+[translations[l] for l in ['es','it','fr']]
 if key.isascii() and key.upper()!=key and '{game}' not in key:
  rows.setdefault(key.upper(),[key.upper()]+[translations[l].upper() for l in ['es','it','fr']])
for index,key in data['misc_indices'].items():
 rows['@misc:'+index]=[key]+[data['strings'][key][l] for l in ['es','it','fr']]
def cstring(s):return json.dumps(s,ensure_ascii=False)
c='/* Generated by localization/generate.py; edit localization/catalog.json. */\n'
c+='static const char* const kLocalizedStrings[][4] = {\n'
for key,row in sorted(rows.items()):
 # The first column is the lookup key, English fallback lives at the call site.
 c+='    {'+', '.join(cstring(s) for s in [key]+row[1:])+'},\n'
c+='};\n'
(root/'src/DETHRACE/common/localization_catalog.h').write_text(c)
j='''// Generated by localization/generate.py; edit localization/catalog.json.
package com.dethrace.android;
import java.util.HashMap;
import java.util.Map;
final class UiLanguage {
    private static int language;
    private static final Map<String,String[]> STRINGS = new HashMap<>();
    static {
'''
for key,tr in data['strings'].items():
 j+='        STRINGS.put('+cstring(key)+',new String[]{'+','.join(cstring(tr[l]) for l in ['es','it','fr'])+'});\n'
j+='''    }
    static String normalize(String code) {
        return "es".equals(code)||"it".equals(code)||"fr".equals(code) ? code : "en";
    }
    static void set(String code) {
        String safe=normalize(code);
        language="es".equals(safe)?1:"it".equals(safe)?2:"fr".equals(safe)?3:0;
    }
    static String text(String value) {
        if(language==0 || value==null) return value;
        String[] exact=STRINGS.get(value);
        if(exact!=null) return exact[language-1];
        for(Map.Entry<String,String[]> entry:STRINGS.entrySet()) {
            String key=entry.getKey();int marker=key.indexOf("{game}");
            if(marker<0) continue;
            String start=key.substring(0,marker),end=key.substring(marker+6);
            if(value.startsWith(start)&&value.endsWith(end)&&value.length()>=start.length()+end.length()) {
                String game=value.substring(start.length(),value.length()-end.length());
                return entry.getValue()[language-1].replace("{game}",game);
            }
        }
        if(value.contains("\\n")) {
            String[] lines=value.split("\\n",-1);
            for(int i=0;i<lines.length;i++)lines[i]=text(lines[i]);
            return String.join("\\n",lines);
        }
        for(String suffix:new String[]{"  ›"," — Installed"," — Import needed"}) {
            if(value.endsWith(suffix))return text(value.substring(0,value.length()-suffix.length()))+textSuffix(suffix);
        }
        return value;
    }
    private static String textSuffix(String value) {
        String[] translated=STRINGS.get(value);return translated==null?value:translated[language-1];
    }
    static String[] labels(String[] values) {
        String[] result=values.clone();for(int i=0;i<result.length;i++)result[i]=text(result[i]);return result;
    }
}
'''
(root/'android/app/src/main/java/com/dethrace/android/UiLanguage.java').write_text(j)
print('Generated',len(rows),'native keys and',len(data['strings']),'launcher keys')
